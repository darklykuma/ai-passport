#!/usr/bin/env python3
"""Regenerate main/rift_champs.{h,c} from the zh_CN champion mapping.

Input: docs/design/rift-board/champions_zh.json (tracked), produced from
Data Dragon zh_CN champion.json. Upstream stores the epithet in the "name"
field and the proper name in "title"; champions_zh.json is already
normalized (name = display proper name, compound names keep the first
segment, full name in name_full).

The generated .c deliberately keeps every non-table byte ASCII so that
tools/gen_rift_charset.py and tests/test_rift_ui_glyphs.py inventory
exactly the champion-name glyphs when they scan it.
"""
import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "docs" / "design" / "rift-board" / "champions_zh.json"
OUT_H = ROOT / "main" / "rift_champs.h"
OUT_C = ROOT / "main" / "rift_champs.c"

doc = json.load(io.open(SRC, encoding="utf-8"))
entries = sorted((k, v["name"]) for k, v in doc["champions"].items())
for key, zh in entries:
    if not key or not zh or '"' in key or '"' in zh or "\\" in key or "\\" in zh:
        sys.exit(f"unsafe table entry: {key!r} -> {zh!r}")

OUT_H.write_text(
    "// rift_champs.h — zh_CN champion display names. GENERATED by\n"
    "// tools/gen_rift_champs.py from docs/design/rift-board/champions_zh.json;\n"
    "// do not hand-edit.\n"
    "#pragma once\n\n"
    "// Map a feed champion id (\"Jayce\") to its zh_CN display name;\n"
    "// returns id itself when the table has no entry.\n"
    "const char *rift_champ_zh(const char *id);\n"
    "// Number of entries in the mapping table.\n"
    "int rift_champ_count(void);\n",
    encoding="utf-8")

rows = "\n".join(f'    {{"{k}", "{zh}"}},' for k, zh in entries)
OUT_C.write_text(
    "// rift_champs.c — GENERATED by tools/gen_rift_champs.py; do not\n"
    "// hand-edit. Sorted by id for binary search.\n"
    '#include "rift_champs.h"\n\n'
    "#include <string.h>\n\n"
    "typedef struct {\n"
    "    const char *id;\n"
    "    const char *zh;\n"
    "} rift_champ_entry_t;\n\n"
    "static const rift_champ_entry_t TABLE[] = {\n"
    f"{rows}\n"
    "};\n\n"
    "int rift_champ_count(void) {\n"
    "    return (int)(sizeof TABLE / sizeof TABLE[0]);\n"
    "}\n\n"
    "const char *rift_champ_zh(const char *id) {\n"
    "    if (!id) return \"\";\n"
    "    int lo = 0, hi = rift_champ_count() - 1;\n"
    "    while (lo <= hi) {\n"
    "        int mid = (lo + hi) / 2;\n"
    "        int c = strcmp(id, TABLE[mid].id);\n"
    "        if (c == 0) return TABLE[mid].zh;\n"
    "        if (c < 0) hi = mid - 1;\n"
    "        else lo = mid + 1;\n"
    "    }\n"
    "    return id;\n"
    "}\n",
    encoding="utf-8")

print(f"wrote {OUT_H.relative_to(ROOT)} and {OUT_C.relative_to(ROOT)} "
      f"({len(entries)} champions, patch {doc['patch']})")
