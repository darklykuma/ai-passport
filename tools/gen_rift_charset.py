#!/usr/bin/env python3
"""Regenerate assets/fonts/rift_charset.txt from the RIFT BOARD UI sources.
The charset is the codepoint inventory for tools/gen_rift_fonts.sh;
tests/test_rift_ui_glyphs.py fails when UI copy and the charset drift apart,
so run this after every copy change and regenerate the fonts."""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [
    ROOT / "main" / "rift_app.c",
    ROOT / "main" / "rift_view.c",
    ROOT / "main" / "rift_model.c",
]
OUT = ROOT / "assets" / "fonts" / "rift_charset.txt"

# Every non-ASCII codepoint in the sources gets a glyph: a hand-picked
# CJK class once missed "·" (U+00B7) and shipped boxes on every page.
NON_ASCII = re.compile(r"[^\x00-\x7f]")

chars = set()
for src in SOURCES:
    chars.update(NON_ASCII.findall(src.read_text(encoding="utf-8")))

OUT.write_text(
    "# RIFT BOARD UI CJK charset — generated by tools/gen_rift_charset.py\n"
    "# from main/rift_{app,view,model}.c. ASCII (0x20-0x7E) is added by the\n"
    "# generator separately. Do not hand-edit; regenerate instead.\n"
    + "".join(sorted(chars))
    + "\n",
    encoding="utf-8",
)
print(f"wrote {OUT.relative_to(ROOT)} ({len(chars)} codepoints)")
